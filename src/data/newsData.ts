export function getNewsBySlug(slug: string): NewsPost | undefined {
  if (!slug) return undefined;
  const cleanSlug = slug.toLowerCase().replace(/^\/+|\/+$/g, '');
  return NEWS_POSTS.find(
    (item) => item.slug.toLowerCase() === cleanSlug || item.id.toLowerCase() === cleanSlug
  );
}

export function getLatestNews(limit?: number): NewsPost[] {
  const sorted = [...NEWS_POSTS].sort(
    (a, b) => new Date(b.date).getTime() - new Date(a.date).getTime()
  );
  return limit ? sorted.slice(0, limit) : sorted;
}
